const PHRASE_KEYS = Object.keys(HI).sort((a, b) => b.length - a.length);
const WORD_KEYS = Object.keys(WORDS).sort((a, b) => b.length - a.length);
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function t(input) {
  const raw = String(input ?? "").replace(/&amp;/g, "&");
  let language = "en";
  try { language = window.localStorage.getItem(LANGUAGE_STORAGE_KEY) || "en"; } catch { /* browser storage may be disabled */ }
  if (language !== "hi") return raw;
  const leading = raw.match(/^\s*/)?.[0] || "";
  const trailing = raw.match(/\s*$/)?.[0] || "";
  const core = raw.trim();
  if (!core) return raw;
  if (HI[core]) return `${leading}${HI[core]}${trailing}`;
  let result = core;
  for (const phrase of PHRASE_KEYS) {
    if (!phrase.includes(" ") || phrase.length < 4) continue;
    result = result.replace(new RegExp(escapeRegExp(phrase), "g"), HI[phrase]);
  }
  for (const word of WORD_KEYS) {
    result = result.replace(new RegExp(`\\b${escapeRegExp(word)}\\b`, "g"), WORDS[word]);
  }
  return `${leading}${result}${trailing}`;
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try { return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "hi" ? "hi" : "en"; }
    catch { return "en"; }
  });
  const setLanguage = useCallback((next) => {
    const resolved = next === "hi" ? "hi" : "en";
    try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, resolved); } catch { /* optional persistence */ }
    setLanguageState(resolved);
  }, []);
  const toggleLanguage = useCallback(() => setLanguage(language === "en" ? "hi" : "en"), [language, setLanguage]);
  const value = useMemo(() => ({ language, setLanguage, toggleLanguage }), [language, setLanguage, toggleLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}

export function LanguageToggle() {
  const { language, toggleLanguage } = useLanguage();
  return <button type="button" className="language-toggle" onClick={toggleLanguage} aria-label={language === "en" ? "हिंदी में बदलें" : "Switch to English"} title={language === "en" ? "हिंदी में बदलें" : "Switch to English"}>{language === "en" ? "हिंदी" : "English"}</button>;
}
