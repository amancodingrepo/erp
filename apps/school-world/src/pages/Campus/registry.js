const lazyCache = new Map();

export function isNative(href) {
  return Object.prototype.hasOwnProperty.call(NATIVE_SCREENS, href);
}

export function nativeComponent(href) {
  if (!isNative(href)) return null;
  if (!lazyCache.has(href)) {
    const [batch, name] = NATIVE_SCREENS[href];
    lazyCache.set(href, React.lazy(() => BATCH_LOADERS[batch]().then((module) => ({ default: module[name] }))));
  }
  return lazyCache.get(href);
}

